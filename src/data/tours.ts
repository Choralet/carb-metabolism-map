import type { Part } from './types';

/**
 * Study mode: guided walkthroughs that step through a pathway in lecture order, one arrow at a time.
 *
 * A chapter follows its slides: each step points at one arrow (`edge`) or, for a step with no arrow of its own, a
 * molecule node (`node`), says in a sentence or two what happens there, and cites its slide. Only what the slides
 * show, as everywhere else, in plain words. Chapter and step ids are permanent: progress (`localStorage
 * 'atlas-study'`) keys on them. Final-exam material only (Parts III and IV); `npm run check` validates every step.
 */
export interface TourStep {
  id: string;
  /** The arrow this step animates. */
  edge?: string;
  /** A molecule to show instead, for a step that is about where something ends up rather than an arrow. */
  node?: string;
  /** Run the animation from the arrow's head to its tail: a reversible step, read the other way (glycerol breakdown). */
  back?: boolean;
  /** More arrows that light up with this one, for a step that says one thing about several (one precursor, four products). */
  also?: string[];
  /** Short heading: what happens, in a few words. */
  title: string;
  /** The narration: one or two sentences. */
  say: string;
  slide: string;
}

